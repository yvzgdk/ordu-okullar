-- et_detay Tablosunun Oluşturulması
CREATE TABLE IF NOT EXISTS public.et_detay (
    id bigint generated by default as identity primary key,
    institution_id bigint references public.kurum_kayit(id) on delete cascade not null,
    kat text,
    sinif_lab text,
    et_tipi text,
    et_yonu text,
    et_boyutu text,
    et_durumu text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);
