-- 2. Institutions (Kurum Kayıt) Tablosu
CREATE TABLE public.kurum_kayit (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    district_id bigint references public.districts(id),
    code text,
    cbs1 text,
    cbs2 text,
    name text not null,
    bds integer,
    status text,
    related_institution_id bigint references public.kurum_kayit(id),
    infra_owner text,
    is_fatih boolean default false,
    faz text,
    altyapi text,
    infrastructure_plan text,
    internet_type text,
    board_owner text,
    vestel_black_boards integer default 0,
    vestel_grey_boards integer default 0,
    arcelik_boards integer default 0,
    aidata_boards integer default 0,
    total_boards integer default 0,
    director text,
    director_phone text,
    has_bt_class boolean default false,
    bt_labs jsonb default '[]'::jsonb,
    has_infrastructure boolean default false,
    altyapi_planlama text
);
