-- 05_board_transfers.sql
-- Okullar arası etkileşimli tahta transfer geçmişini tutan tablo

CREATE TABLE IF NOT EXISTS public.board_transfers (
    id bigint generated by default as identity primary key,
    date date not null default CURRENT_DATE,
    board_type text not null,
    count integer not null default 1,
    from_institution_id bigint references public.kurum_kayit(id) on delete set null,
    to_institution_id bigint references public.kurum_kayit(id) on delete set null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Hızlı sorgular için indeksler
CREATE INDEX IF NOT EXISTS idx_board_transfers_from_inst ON public.board_transfers(from_institution_id);
CREATE INDEX IF NOT EXISTS idx_board_transfers_to_inst ON public.board_transfers(to_institution_id);
CREATE INDEX IF NOT EXISTS idx_board_transfers_date ON public.board_transfers(date);
