-- 2. Kurum Kayıt (Okullar) Tablosu
CREATE TABLE IF NOT EXISTS public.kurum_kayit (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    district_id bigint references public.districts(id),
    code text,
    cbs1 text,
    cbs2 text,
    name text not null,
    bds integer,
    status text default 'ev_sahibi',
    related_institution_id bigint references public.kurum_kayit(id),
    infra_owner text,
    is_fatih boolean default false,
    faz text default 'Faz Yok',
    altyapi text,
    infrastructure_plan text,
    internet_type text,
    board_owner text,
    vestel_black_boards integer default 0,
    vestel_grey_boards integer default 0,
    arcelik_boards integer default 0,
    aidata_boards integer default 0,
    total_boards integer default 0,
    director text,
    director_phone text,
    has_bt_class boolean default false,
    bt_labs jsonb default '[]'::jsonb,
    has_infrastructure boolean default false,
    altyapi_planlama text
);

-- 3. Etkileşimli Tahta Detay Tablosu (Bina, Kat, Sınıf bazında tekil tahtalar)
CREATE TABLE IF NOT EXISTS public.et_detay (
    id bigint generated by default as identity primary key,
    institution_id bigint references public.kurum_kayit(id) on delete cascade not null,
    bina varchar(50),
    kat text,
    sinif_lab text,
    et_tipi text,
    et_yonu text,
    et_boyutu text,
    et_durumu text default 'Kullanımda',
    calisiyor_mu boolean default true,
    aciklama text,
    is_transferred boolean default false,
    transfer_tarihi date,
    resmi_yazi_no text,
    transfer_from bigint references public.kurum_kayit(id) on delete set null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4. BTR (Bilişim Teknolojileri Rehber Öğretmenleri) / YOS Tablosu
CREATE TABLE IF NOT EXISTS public.btr_records (
    id bigint generated by default as identity primary key,
    name text not null,
    surname text not null,
    brans text,
    phone text,
    email text,
    district_id bigint references public.districts(id) on delete set null,
    institution_id bigint references public.kurum_kayit(id) on delete set null,
    institution_id_2 bigint references public.kurum_kayit(id) on delete set null,
    assignment_date date,
    status text default 'Aktif',
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 5. Okullar Arası Tahta Transfer Geçmişi Tablosu
CREATE TABLE IF NOT EXISTS public.board_transfers (
    id bigint generated by default as identity primary key,
    date date not null default CURRENT_DATE,
    board_type text not null,
    count integer not null default 1,
    from_institution_id bigint references public.kurum_kayit(id) on delete set null,
    to_institution_id bigint references public.kurum_kayit(id) on delete set null,
    official_letter_no text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 6. ET İhtiyaç Takip Tablosu
CREATE TABLE IF NOT EXISTS public.et_ihtiyac (
    id bigint generated by default as identity primary key,
    district_id bigint references public.districts(id) on delete set null,
    institution_id bigint references public.kurum_kayit(id) on delete cascade not null,
    bina text,
    kat text,
    sinif_lab text not null,
    et_yonu text,
    et_boyutu text,
    aciklama text,
    durum text default 'Beklemede',
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 7. Geriye Uyumluluk İçin VIEW (Eğer eski kodlar 'institutions' ararsa)
CREATE OR REPLACE VIEW public.institutions AS SELECT * FROM public.kurum_kayit;

-- İndeksler (Hızlı filtreleme ve listeleme için)
CREATE INDEX IF NOT EXISTS idx_kurum_district ON public.kurum_kayit(district_id);
CREATE INDEX IF NOT EXISTS idx_kurum_code ON public.kurum_kayit(code);
CREATE INDEX IF NOT EXISTS idx_et_detay_inst ON public.et_detay(institution_id);
CREATE INDEX IF NOT EXISTS idx_btr_inst ON public.btr_records(institution_id);
CREATE INDEX IF NOT EXISTS idx_transfers_from ON public.board_transfers(from_institution_id);
CREATE INDEX IF NOT EXISTS idx_transfers_to ON public.board_transfers(to_institution_id);
CREATE INDEX IF NOT EXISTS idx_et_ihtiyac_inst ON public.et_ihtiyac(institution_id);
CREATE INDEX IF NOT EXISTS idx_et_ihtiyac_dist ON public.et_ihtiyac(district_id);

-- RLS (Row Level Security) - Tabloları okuma ve yazmaya açma
ALTER TABLE public.districts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kurum_kayit ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.et_detay ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.btr_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.board_transfers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.et_ihtiyac ENABLE ROW LEVEL SECURITY;

